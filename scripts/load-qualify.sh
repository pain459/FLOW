#!/bin/sh
# Destructive snapshot restoration is confined to this newly created disposable project.
set -eu
cd "$(dirname "$0")/.."
export COMPOSE_PROJECT_NAME=chaosloop-load-baseline
export API_PORT=18080 PROMETHEUS_PORT=18090 GRAFANA_PORT=18000 LOG_COLLECTOR_PORT=34224
export LOCUST_UI_PORT=18089
export SEED_VERSION=pulsepay-v1
test "$COMPOSE_PROJECT_NAME" = chaosloop-load-baseline
dc() { docker compose -f compose.yaml -f compose.load.yaml "$@"; }
mkdir -p artifacts/load-runs
snapshot=artifacts/load-runs/qualification-seed.dump
if [ -f "$snapshot" ] && [ "${RESUME_QUALIFICATION:-false}" != true ]; then
  echo 'Snapshot exists. Use RESUME_QUALIFICATION=true to repeat from it; retained evidence is never silently replaced.' >&2
  exit 1
fi
dc --profile observability up -d --wait
# Freeze one built image for the whole qualification. Docker build attestations can
# change an image ID even with cached layers; never weaken provenance comparison.
export LOAD_IMAGE=pulsepay-load:v1
dc build load-controller
qualified_image="pulsepay-load:qualified-$(date -u +%Y%m%dT%H%M%SZ)"
docker image tag pulsepay-load:v1 "$qualified_image"
export LOAD_IMAGE="$qualified_image" LOAD_IMAGE_PREBUILT=true
if [ ! -f "$snapshot" ]; then
  dc run --rm --no-deps seed > artifacts/load-runs/qualification-seed.json
  dc run --rm --no-deps verifier python -m verifier.main --once > artifacts/load-runs/qualification-verifier-seed.json
  dc exec -T postgres sh -c 'pg_dump -U "$POSTGRES_USER" -d "$POSTGRES_DB" --format=custom' > "$snapshot"
fi
restore() {
  test "$COMPOSE_PROJECT_NAME" = chaosloop-load-baseline
  dc stop api outbox-relay event-worker verifier >/dev/null
  dc exec -T postgres sh -c 'pg_restore -U "$POSTGRES_USER" -d "$POSTGRES_DB" --clean --if-exists --single-transaction' < "$snapshot"
  dc exec -T redis redis-cli FLUSHALL >/dev/null
  dc --profile observability up -d --wait api outbox-relay event-worker verifier >/dev/null
}
run_ids=''
invocation=$(date -u +%Y%m%dT%H%M%SZ)
if [ "${RESUME_QUALIFICATION:-false}" = true ]; then restore; fi
for repetition in 1 2 3; do
  if [ "$repetition" != 1 ]; then restore; fi
  echo "Nominal qualification repetition $repetition"
  PROFILE=nominal DURATION=120 WARMUP=30 USERS=20 RATE=20 sh scripts/load-run.sh > "artifacts/load-runs/qualification-$invocation-nominal-$repetition.log" 2>&1
  run_id=$(dc run --rm --no-deps -T load-controller python -c 'from pathlib import Path; from load_generator.controller.lifecycle import read_json; print(read_json(Path("/reports/latest.json"))["run_id"])')
  run_ids="$run_ids --run-id $run_id"
done
# Identifiers are generated by the controller and validated again by its parser.
dc run --rm --no-deps -T load-controller python -m load_generator.controller.cli baseline $run_ids > "artifacts/load-runs/qualification-$invocation-baseline.json"
for profile in read_heavy write_heavy hot_accounts burst; do
  restore
  echo "Qualification trial $profile"
  if [ "$profile" = burst ]; then
    PROFILE="$profile" DURATION=120 WARMUP=30 USERS=60 sh scripts/load-run.sh > "artifacts/load-runs/qualification-$invocation-$profile.log" 2>&1
  else
    PROFILE="$profile" DURATION=120 WARMUP=30 sh scripts/load-run.sh > "artifacts/load-runs/qualification-$invocation-$profile.log" 2>&1
  fi
done
echo 'Qualification complete; retained project/volumes and artifacts/load-runs/ evidence.'
