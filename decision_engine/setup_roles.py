"""One-shot credential provisioning. No secrets printed or sent to inference."""

import asyncio
import os
import re

import asyncpg


async def main():
    c = await asyncpg.connect(
        host="postgres",
        user=os.environ["POSTGRES_USER"],
        password=os.environ["POSTGRES_PASSWORD"],
        database=os.environ["POSTGRES_DB"],
        command_timeout=5,
    )
    async with c.transaction():
        for role, env in (
            ("pulsepay_decision", "DECISION_PASSWORD"),
            ("pulsepay_decision_migrator", "DECISION_MIGRATOR_PASSWORD"),
            ("pulsepay_evaluator", "EVALUATOR_PASSWORD"),
        ):
            secret = os.environ[env]
            if not re.fullmatch(r"[a-f0-9]{48}", secret):
                raise ValueError("role secret must be generated by intelligence-setup")
            exists = await c.fetchval("SELECT 1 FROM pg_roles WHERE rolname=$1", role)
            if not exists:
                await c.execute(
                    f"CREATE ROLE {role} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT PASSWORD '{secret}'"
                )
            else:
                await c.execute(f"ALTER ROLE {role} PASSWORD '{secret}'")
        for schema in ("decision_intel", "decision_evaluation"):
            await c.execute(
                f"CREATE SCHEMA IF NOT EXISTS {schema} AUTHORIZATION pulsepay_decision_migrator"
            )
        await c.execute("ALTER ROLE pulsepay_decision SET statement_timeout='5s'")
        await c.execute("ALTER ROLE pulsepay_evaluator SET statement_timeout='5s'")
    await c.close()
    print('{"status":"PROVISIONED","roles":3,"secrets_printed":false}')


if __name__ == "__main__":
    asyncio.run(main())
